// Regenerates deploy/leaderboard-v2-artifact.js from the Foundry build (run `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { keccak256, id, AbiCoder, concat, getCreate2Address } from "ethers";
const a = JSON.parse(readFileSync("out/LeaderboardV2.sol/LeaderboardV2.json", "utf8"));
const commit = execSync("git rev-parse --short HEAD").toString().trim();
// CREATE2 via the canonical deterministic deployer (works from EOAs and smart accounts alike).
const FACTORY = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const SALT = id("asteroid-shooter/LeaderboardV2/v1");
const ARGS = ["0x833589fCD6eDb6E08f4c7C32D4f71b54bdA02913", "0xcEFB2484932595ffFC809a27B8A5b106A8E1715A",
  "0xACfCA8Bc6567E7DB35AD8C814756695dad1cfB30", "0xE2741163168B434Ac58373834E0c22a5A253C962"];
const initcode = concat([a.bytecode.object, AbiCoder.defaultAbiCoder().encode(["address","address","address","address"], ARGS)]);
const expected = getCreate2Address(FACTORY, SALT, keccak256(initcode));
const art = {
  factory: FACTORY, salt: SALT, args: ARGS, expectedAddress: expected,
  runtimeHash: keccak256(a.deployedBytecode.object),
  contract: "LeaderboardV2",
  compiler: a.metadata.compiler.version,
  optimizer: a.metadata.settings.optimizer,
  evmVersion: a.metadata.settings.evmVersion,
  sourceCommit: commit,
  bytecodeHash: keccak256(a.bytecode.object),
  abi: a.abi,
  bytecode: a.bytecode.object,
};
writeFileSync("deploy/leaderboard-v2-artifact.js", "// GENERATED by scripts/gen-deploy-page.mjs. Do not edit.\nwindow.LEADERBOARD_V2_ARTIFACT = " + JSON.stringify(art) + ";\n");
console.log("artifact", art.compiler, art.bytecodeHash, "from", commit, "expected", expected);
