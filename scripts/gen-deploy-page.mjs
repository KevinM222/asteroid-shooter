// Regenerates deploy/leaderboard-v2-artifact.js from the Foundry build (run `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { keccak256 } from "ethers";
const a = JSON.parse(readFileSync("out/LeaderboardV2.sol/LeaderboardV2.json", "utf8"));
const commit = execSync("git rev-parse --short HEAD").toString().trim();
const art = {
  contract: "LeaderboardV2",
  compiler: a.metadata.compiler.version,
  optimizer: a.metadata.settings.optimizer,
  evmVersion: a.metadata.settings.evmVersion,
  sourceCommit: commit,
  bytecodeHash: keccak256(a.bytecode.object),
  abi: a.abi,
  bytecode: a.bytecode.object,
};
writeFileSync("deploy/leaderboard-v2-artifact.js", "// GENERATED by scripts/gen-deploy-page.mjs. Do not edit.\nwindow.LEADERBOARD_V2_ARTIFACT = " + JSON.stringify(art) + ";\n");
console.log("artifact", art.compiler, art.bytecodeHash, "from", commit);
